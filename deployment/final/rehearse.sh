#!/usr/bin/env bash
set -euo pipefail
root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)"
case "${1:-checker}" in
    checker)
        export LOAD_PROFILE=checker LOAD_REST_RPS="${LOAD_REST_RPS:-100}"
        export LOAD_DURATION="${LOAD_DURATION:-15m}"
        ;;
    combined)
        export LOAD_PROFILE=load LOAD_REST_RPS="${LOAD_REST_RPS:-1000}"
        export LOAD_DURATION="${LOAD_DURATION:-15m}"
        ;;
    soak)
        export LOAD_PROFILE=soak LOAD_REST_RPS="${LOAD_REST_RPS:-1000}"
        export LOAD_DURATION="${LOAD_DURATION:-4h}"
        ;;
    *) echo "Usage: $0 {checker|combined|soak}" >&2; exit 2 ;;
esac
export LOAD_CAPACITY=pr-final LOAD_MONITORING=1 LOAD_DIAGNOSTICS=1
export LOAD_TEAM_COUNT=7 LOAD_SPECTATORS="${LOAD_SPECTATORS:-42}"
export LOAD_API_REPLICAS=2 LOAD_RECEIVER_REPLICAS=1 LOAD_WORKER_REPLICAS=2
export LOAD_WORKER_CONCURRENCY=8 LOAD_WORKER_DATABASE_MAX_CONNS=8
export LOAD_CHECKER_MEMORY_LIMIT_MB=1024
export LOAD_PUTS=5,10,3 LOAD_ROUND_TIME=60 LOAD_CHECKER_TIMEOUT=20
export LOAD_PFR=1
export LOAD_API_DATABASE_MAX_CONNS=8 LOAD_API_DATABASE_MIN_CONNS=4
export LOAD_API_HTTP_MAX_INFLIGHT=128 LOAD_API_GOGC=100
export LOAD_PGBOUNCER_API_CONNECTIONS=16 LOAD_PGBOUNCER_API_MIN_CONNECTIONS=4
export LOAD_DATABASE_STORAGE=disk LOAD_CONTAINER_LOGGING=local
export LOAD_CHECKPOINT_INTERVAL="$LOAD_DURATION"
exec make -C "$root/backend" test-load
