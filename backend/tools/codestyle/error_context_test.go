func TestErrorContextAcceptsConstantsParametersAliasesAndSentinels(t *testing.T) {
	for _, source := range []string{
		`package p; import "fmt"; func f(err error) error { const location = "p.f"; return fmt.Errorf("%s - read: %w", location, err) }`,
		`package p; import(format "fmt"; faults "errors"); var ErrSentinel = faults.New("sentinel"); func f() error { const location = "p.f"; return format.Errorf("%s - invalid input", location) }`,
		`package p; import "fmt"; func f() func() error { const location = "p.f"; return func() error { return fmt.Errorf("%s - callback failed", location) } }`,
		`package p; import "fmt"; func f() func() error { const location = "p.f"; return func() error { const location = "p.callback"; return fmt.Errorf("%s - callback failed", location) } }`,
		`package p; import "fmt"; func f(location string, err error) error { return fmt.Errorf("%s - operation: %w", location, err) }`,
		`package p; import "fmt"; func f(location string) func() error { return func() error { return fmt.Errorf("%s - operation failed", location) } }`,
		`package p; func f(err error) error { return err }`,
		`package p; import "fmt"; func f(fmt interface{ Errorf(string, ...any) error }) error { return fmt.Errorf("domain method") }`,
		`package p; import "errors"; func f(errors interface{ New(string) error }) error { return errors.New("domain method") }`,
		`package p; import fmt "example.com/domain"; func f() error { return fmt.Errorf("domain method") }`,
		`package p; import "fmt"; const message = "%s - problem"; func f() error { const location = "p.f"; return fmt.Errorf(message, location) }`,
		`package p; import "fmt"; var callback = func() error { const location = "p.callback"; return fmt.Errorf("%s - callback failed", location) }`,
		`package p; import . "fmt"; func f() error { const location = "p.f"; return Errorf("%s - failed", location) }`,
	} {
		t.Run(source, func(t *testing.T) {
			issues, err := checkErrorSource("fixture.go", []byte(source))
			if err != nil || len(issues) != 0 {
				t.Fatalf("valid error context was rejected: %+v, %v", issues, err)
			}
		})
	}
}

func TestErrorContextRejectsUnattributedRuntimeConstructors(t *testing.T) {
	for _, source := range []string{
		`package p; import "fmt"; func f() error { return fmt.Errorf("failed") }`,
		`package p; import "fmt"; func f() error { return fmt.Errorf("p.f - failed") }`,
		`package p; import "fmt"; const location = "p"; func f() error { return fmt.Errorf("%s - failed", location) }`,
		`package p; import "fmt"; func f() error { location := "p.f"; return fmt.Errorf("%s - failed", location) }`,
		`package p; import "fmt"; func f() error { const location = ""; return fmt.Errorf("%s - failed", location) }`,
		`package p; import "fmt"; func f(location int) error { return fmt.Errorf("%s - failed", location) }`,
		`package p; import "errors"; func f() error { return errors.New("failed") }`,
		`package p; import "fmt"; func f() error { const location = "p.f"; return fmt.Errorf("%s: failed", location) }`,
		`package p; import "fmt"; func f() error { const location = "p.f"; return fmt.Errorf("%v - failed", location) }`,
		`package p; import "fmt"; func f() error { const source = "p.f"; return fmt.Errorf("%s - failed", source) }`,
		`package p; import "fmt"; func f() (location string, err error) { return "", fmt.Errorf("%s - failed", location) }`,
		`package p; import . "errors"; func f() error { return New("failed") }`,
		`package p; import "fmt"; var callback = func() error { return fmt.Errorf("failed") }`,
	} {
		t.Run(source, func(t *testing.T) {
			issues, err := checkErrorSource("fixture.go", []byte(source))
			if err != nil || len(issues) != 1 || issues[0].position.Filename != "fixture.go" {
				t.Fatalf("unattributed constructor was not diagnosed once: %+v, %v", issues, err)
			}
		})
	}
}

func TestErrorContextExcludesGeneratedTestsAndDoesNotScanText(t *testing.T) {
	for _, filename := range []string{"fixture_test.go", "integration_test/helpers.go"} {
		issues, err := checkErrorSource(filename, []byte("intentionally not Go source"))
		if err != nil || len(issues) != 0 {
			t.Fatalf("test fixture %s was inspected: %+v, %v", filename, issues, err)
		}
	}
	generated := "// Code generated by fixture. DO NOT EDIT.\npackage p\nimport \"errors\"\nfunc f() error { return errors.New(\"generated\") }"
	issues, err := checkErrorSource("generated.go", []byte(generated))
	if err != nil || len(issues) != 0 {
		t.Fatalf("generated constructors were inspected: %+v, %v", issues, err)
	}
	source := "package p\n// fmt.Errorf(\"comment\")\nvar example = `errors.New(\"string\")`\n"
	issues, err = checkErrorSource("fixture.go", []byte(source))
	if err != nil || len(issues) != 0 {
		t.Fatalf("text was treated as an error constructor: %+v, %v", issues, err)
	}
}

func TestErrorContextParseFailureHasSourceContext(t *testing.T) {
	_, err := checkErrorSource("broken.go", []byte("package p; func f( {"))
	if err == nil || !strings.Contains(err.Error(), "codestyle.checkErrorSource - parse source") {
		t.Fatalf("parse error lacks its operation context: %v", err)
	}
}

func TestErrorContextCLICheckNeverRewritesSource(t *testing.T) {
	path := filepath.Join(t.TempDir(), "source.go")
	source := []byte("package p; import \"errors\"; func f() error { return errors.New(\"failed\") }")
	if err := os.WriteFile(path, source, 0o600); err != nil {
		t.Fatal(err)
	}
	var out, diagnostics bytes.Buffer
	if status := run([]string{"--check-errors", path}, &out, &diagnostics); status != 1 || !strings.Contains(out.String(), "runtime errors.New") {
		t.Fatalf("error check status=%d output=%s diagnostics=%s", status, &out, &diagnostics)
	}
	got, err := os.ReadFile(path)
	if err != nil || !bytes.Equal(got, source) {
		t.Fatal("error check rewrote source")
	}
	if status := run([]string{"--check-errors", "--fix", path}, &out, &diagnostics); status != 2 {
		t.Fatalf("conflicting modes returned %d", status)
	}
}
