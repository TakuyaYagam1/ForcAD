import os

import click

from . import constants

GENERATED_COMPOSE_MARKER = '# Generated by ForcAD for external storage settings.'


def effective_compose_path():
    path = constants.GENERATED_COMPOSE_PATH
    if not path.exists() and not path.is_symlink():
        return constants.FULL_COMPOSE_PATH
    if path.is_symlink() or not path.is_file():
        raise click.ClickException(f'Not a regular generated compose file: {path}')
    try:
        with path.open() as stream:
            marker = stream.readline().strip()
    except OSError as error:
        raise click.ClickException(
            f'Could not inspect generated compose file {path}: {error.strerror}'
        ) from error
    if marker != GENERATED_COMPOSE_MARKER:
        raise click.ClickException(
            f'Refusing to use an unrecognized file at {path}'
        )
    return path


def remove_generated_compose():
    path = constants.GENERATED_COMPOSE_PATH
    if not path.exists() and not path.is_symlink():
        return
    effective_compose_path()
    try:
        path.unlink()
    except OSError as error:
        raise click.ClickException(
            f'Could not remove generated compose file {path}: {error.strerror}'
        ) from error


def compose_command(fast=False):
    """Build the shared Compose prefix; --fast remains a base alias."""
    del fast
    command = [
        'docker', 'compose',
        '--project-directory', str(constants.DEPLOYMENT_DIR),
        '-f', str(effective_compose_path()),
    ]
    if os.getenv('TEST'):
        command += ['-f', str(constants.TESTS_COMPOSE_PATH)]
    return command
