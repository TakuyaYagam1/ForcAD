package operator

import (
	"bufio"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

const generatedComposeMarker = "# Generated by ForcAD for external storage settings."

type projectPaths struct {
	config           string
	configDir        string
	runtime          string
	deployment       string
	canonicalCompose string
	testCompose      string
	generatedCompose string
	adminEnv         string
	postgresEnv      string
	rabbitmqEnv      string
	redisEnv         string
}

func pathsFor(root string) (projectPaths, error) {
	const location = "operator.pathsFor"
	if strings.TrimSpace(root) == "" {
		return projectPaths{}, fmt.Errorf("%s - project root is required", location)
	}
	abs, err := filepath.Abs(root)
	if err != nil {
		return projectPaths{}, fmt.Errorf("%s - resolve project root: %w", location, err)
	}
	deployment := filepath.Join(abs, "deployment", "docker")
	runtime := filepath.Join(abs, "config", "runtime")
	return projectPaths{
		config:           filepath.Join(abs, "config", "config.yml"),
		configDir:        filepath.Join(abs, "config"),
		runtime:          runtime,
		deployment:       deployment,
		canonicalCompose: filepath.Join(deployment, "compose.yml"),
		testCompose:      filepath.Join(deployment, "compose.tests.yml"),
		generatedCompose: filepath.Join(runtime, "compose.external.yml"),
		adminEnv:         filepath.Join(runtime, "admin.env"),
		postgresEnv:      filepath.Join(runtime, "postgres_environment.env"),
		rabbitmqEnv:      filepath.Join(runtime, "rabbitmq_environment.env"),
		redisEnv:         filepath.Join(runtime, "redis_environment.env"),
	}, nil
}

// EffectiveComposePath returns the generated external-storage override when it
// is a regular ForcAD-managed file, otherwise the canonical Compose file.
func EffectiveComposePath(root string) (string, error) {
	paths, err := pathsFor(root)
	if err != nil {
		return "", err
	}
	return effectiveComposePath(paths)
}

// ComposeArgs builds the shared Compose prefix used by operator commands.
func ComposeArgs(root string, includeTests bool) ([]string, error) {
	paths, err := pathsFor(root)
	if err != nil {
		return nil, err
	}
	composePath, err := effectiveComposePath(paths)
	if err != nil {
		return nil, err
	}
	args := []string{
		"docker", "compose",
		"--project-directory", paths.deployment,
		"-f", composePath,
	}
	if includeTests {
		args = append(args, "-f", paths.testCompose)
	}
	return args, nil
}

// RemoveGeneratedCompose removes only the recognized external-storage override.
func RemoveGeneratedCompose(root string) error {
	paths, err := pathsFor(root)
	if err != nil {
		return err
	}
	return removeGeneratedCompose(paths)
}

func effectiveComposePath(paths projectPaths) (string, error) {
	const location = "operator.effectiveComposePath"
	runtimeInfo, err := os.Lstat(paths.runtime)
	if errors.Is(err, os.ErrNotExist) {
		return paths.canonicalCompose, nil
	}
	if err != nil {
		return "", fmt.Errorf("%s - inspect runtime directory: %w", location, err)
	}
	if runtimeInfo.Mode()&os.ModeSymlink != 0 || !runtimeInfo.IsDir() {
		return "", fmt.Errorf("%s - runtime path is not a directory: %s", location, paths.runtime)
	}
	info, err := os.Lstat(paths.generatedCompose)
	if errors.Is(err, os.ErrNotExist) {
		return paths.canonicalCompose, nil
	}
	if err != nil {
		return "", fmt.Errorf("%s - inspect generated Compose file: %w", location, err)
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
		return "", fmt.Errorf("%s - not a regular generated Compose file: %s", location, paths.generatedCompose)
	}
	file, err := openGeneratedCompose(paths, info)
	if err != nil {
		return "", err
	}
	defer func() { _ = file.Close() }()
	line, err := bufio.NewReaderSize(file, 4097).ReadSlice('\n')
	if err != nil {
		if errors.Is(err, bufio.ErrBufferFull) {
			return "", fmt.Errorf("%s - refusing to use an unrecognized file at %s", location, paths.generatedCompose)
		}
		if !errors.Is(err, io.EOF) {
			return "", fmt.Errorf("%s - could not inspect generated Compose file %s: %w", location, paths.generatedCompose, err)
		}
	}
	if strings.TrimSpace(string(line)) != generatedComposeMarker {
		return "", fmt.Errorf("%s - refusing to use an unrecognized file at %s", location, paths.generatedCompose)
	}
	return paths.generatedCompose, nil
}

func openGeneratedCompose(paths projectPaths, info os.FileInfo) (*os.File, error) {
	const location = "operator.openGeneratedCompose"
	file, err := os.Open(paths.generatedCompose)
	if err != nil {
		return nil, fmt.Errorf("%s - read generated Compose file: %w", location, err)
	}
	openedInfo, err := file.Stat()
	if err != nil {
		_ = file.Close()
		return nil, fmt.Errorf("%s - inspect generated Compose file: %w", location, err)
	}
	currentInfo, err := os.Lstat(paths.generatedCompose)
	if err != nil || currentInfo.Mode()&os.ModeSymlink != 0 || !os.SameFile(info, openedInfo) || !os.SameFile(openedInfo, currentInfo) {
		_ = file.Close()
		return nil, fmt.Errorf("%s - generated Compose file changed while opening: %s", location, paths.generatedCompose)
	}
	return file, nil
}
