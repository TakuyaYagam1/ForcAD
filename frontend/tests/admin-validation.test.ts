import assert from "node:assert/strict";
import test from "node:test";
import {
  MAX_TASK_INTEGER_VALUE,
  validateTask,
  validateTeam,
} from "../src/shared/lib/adminValidation.ts";

const team = {
  name: "Team",
  ip: "10.183.101.2",
  token: "0123456789abcdef",
  logo_path: "",
  highlighted: false,
  active: true,
};

const task = {
  name: "Service",
  checker: "check.py",
  gets: 1,
  puts: 1,
  places: 1,
  checker_timeout: 20,
  checker_type: "hackerdom",
  env_path: "",
  get_period: 10,
  default_score: 2500,
  active: true,
};

test("team token validation matches the server's lowercase hex format", () => {
  assert.equal(validateTeam(team), null);
  for (const token of ["", "abc", "0123456789abcdeF", "0123456789abcde_", "0".repeat(17)]) {
    assert.notEqual(validateTeam({ ...team, token }), null);
  }
});

test("a new team can receive a token generated by the server", () => {
  assert.equal(validateTeam({ ...team, token: "" }, true), null);
});

test("task integer fields enforce the API range", () => {
  assert.equal(validateTask({ ...task, gets: MAX_TASK_INTEGER_VALUE }), null);
  assert.notEqual(
    validateTask({ ...task, gets: MAX_TASK_INTEGER_VALUE + 1 }),
    null,
  );
  assert.notEqual(validateTask({ ...task, places: 0 }), null);
  assert.notEqual(validateTask({ ...task, puts: 1.5 }), null);
});
